package com.example.cleanbot.ui.screens

import androidx.compose.foundation.background
import androidx.compose.foundation.border
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.items
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.filled.*
import androidx.compose.material3.*
import androidx.compose.runtime.Composable
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.platform.testTag
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.example.cleanbot.data.CleanBotAppState
import com.example.cleanbot.data.CleanBotRepository
import com.example.cleanbot.model.DirtClassification
import com.example.cleanbot.ui.components.EmptyStateView
import com.example.ui.theme.*
import java.text.SimpleDateFormat
import java.util.*

@Composable
fun DirtDetectionScreen(
    state: CleanBotAppState,
    repository: CleanBotRepository,
    modifier: Modifier = Modifier
) {
    LazyColumn(
        modifier = modifier
            .fillMaxSize()
            .padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        item {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Column {
                    Text("Dirt & Spill Detection Telemetry", color = TextPrimary, fontSize = 18.sp, fontWeight = FontWeight.Bold)
                    Text("Optical & Spectrometry Telemetry Stream", color = TextSecondary, fontSize = 12.sp)
                }

                Button(
                    onClick = { repository.spawnRandomSpill() },
                    colors = ButtonDefaults.buttonColors(containerColor = CyanAccent, contentColor = Navy950),
                    contentPadding = PaddingValues(horizontal = 10.dp, vertical = 6.dp),
                    modifier = Modifier.testTag("btn_trigger_dirt_sim")
                ) {
                    Icon(Icons.Default.Opacity, contentDescription = null, modifier = Modifier.size(16.dp))
                    Spacer(Modifier.width(4.dp))
                    Text("Simulate Spill", fontSize = 11.sp, fontWeight = FontWeight.Bold)
                }
            }
        }

        // Prominent Simulation Disclaimer Banner
        item {
            Card(
                modifier = Modifier.fillMaxWidth(),
                colors = CardDefaults.cardColors(containerColor = Navy800),
                shape = RoundedCornerShape(12.dp)
            ) {
                Row(
                    modifier = Modifier.padding(12.dp),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    Icon(Icons.Default.Info, contentDescription = null, tint = CyanAccent, modifier = Modifier.size(24.dp))
                    Column {
                        Text("SIMULATED SENSOR MODE", color = CyanAccent, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                        Text(
                            "Detections are generated by the simulation engine to test classification and routing. Physical hardware optical sensor integration points are defined in the HAL.",
                            color = TextSecondary,
                            fontSize = 11.sp
                        )
                    }
                }
            }
        }

        // Summary Breakdown by Classification
        item {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                val wetCount = state.dirtEvents.count { it.classification == DirtClassification.WET }
                val dryCount = state.dirtEvents.count { it.classification == DirtClassification.DRY }
                val mixedCount = state.dirtEvents.count { it.classification == DirtClassification.MIXED }

                ClassificationPill(label = "WET SPILLS", count = wetCount, color = CyanAccent, modifier = Modifier.weight(1f))
                ClassificationPill(label = "DRY DEBRIS", count = dryCount, color = StatusAmber, modifier = Modifier.weight(1f))
                ClassificationPill(label = "MIXED", count = mixedCount, color = ElectricBlue, modifier = Modifier.weight(1f))
            }
        }

        // Detection Events Feed
        item {
            Text("Detection Telemetry Log (${state.dirtEvents.size})", color = TextPrimary, fontSize = 14.sp, fontWeight = FontWeight.Bold)
        }

        if (state.dirtEvents.isEmpty()) {
            item {
                Card(
                    modifier = Modifier.fillMaxWidth(),
                    colors = CardDefaults.cardColors(containerColor = Navy800),
                    shape = RoundedCornerShape(12.dp)
                ) {
                    EmptyStateView(
                        title = "No Dirt Detected Yet",
                        subtitle = "As the robot sweeps rooms, detected debris will be classified and logged here.",
                        icon = Icons.Default.FilterVintage
                    )
                }
            }
        } else {
            items(state.dirtEvents.reversed()) { event ->
                Card(
                    modifier = Modifier.fillMaxWidth(),
                    colors = CardDefaults.cardColors(containerColor = Navy800),
                    shape = RoundedCornerShape(12.dp)
                ) {
                    Column(modifier = Modifier.padding(14.dp)) {
                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.SpaceBetween,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                                val pillColor = when (event.classification) {
                                    DirtClassification.WET -> CyanAccent
                                    DirtClassification.DRY -> StatusAmber
                                    DirtClassification.MIXED -> ElectricBlue
                                    DirtClassification.UNKNOWN -> TextMuted
                                }
                                Box(
                                    modifier = Modifier
                                        .clip(RoundedCornerShape(4.dp))
                                        .background(pillColor.copy(alpha = 0.2f))
                                        .border(1.dp, pillColor, RoundedCornerShape(4.dp))
                                        .padding(horizontal = 6.dp, vertical = 2.dp)
                                ) {
                                    Text(event.classification.displayName, color = pillColor, fontSize = 10.sp, fontWeight = FontWeight.Bold)
                                }
                                Text(event.category.displayName, color = TextPrimary, fontSize = 14.sp, fontWeight = FontWeight.Bold)
                            }

                            Text("${event.confidencePercent}% Confidence", color = StatusGreen, fontSize = 11.sp, fontWeight = FontWeight.Bold)
                        }

                        Spacer(Modifier.height(8.dp))

                        Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                            Text("Room: ${event.roomName}", color = TextSecondary, fontSize = 12.sp)
                            val timeStr = SimpleDateFormat("HH:mm:ss", Locale.getDefault()).format(Date(event.timestamp))
                            Text(timeStr, color = TextMuted, fontSize = 11.sp)
                        }

                        Spacer(Modifier.height(6.dp))

                        Box(
                            modifier = Modifier
                                .fillMaxWidth()
                                .background(Navy900, RoundedCornerShape(6.dp))
                                .padding(8.dp)
                        ) {
                            Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                                Icon(Icons.Default.CleaningServices, contentDescription = null, tint = CyanAccent, modifier = Modifier.size(16.dp))
                                Column {
                                    Text("Recommended Cleaning Protocol:", color = TextMuted, fontSize = 10.sp)
                                    Text(event.recommendedMethod, color = TextPrimary, fontSize = 11.sp, fontWeight = FontWeight.Medium)
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

@Composable
private fun ClassificationPill(label: String, count: Int, color: androidx.compose.ui.graphics.Color, modifier: Modifier = Modifier) {
    Card(
        modifier = modifier,
        colors = CardDefaults.cardColors(containerColor = Navy800),
        shape = RoundedCornerShape(10.dp)
    ) {
        Column(modifier = Modifier.padding(10.dp)) {
            Text(label, color = TextMuted, fontSize = 10.sp, fontWeight = FontWeight.Bold)
            Text("$count", color = color, fontSize = 18.sp, fontWeight = FontWeight.Bold)
        }
    }
}
